"""Create the NOT gate report using native Logisim images and actual GHDL VCD."""
from pathlib import Path
from reportlab.pdfgen import canvas
from reportlab.lib.pagesizes import A4
from reportlab.lib import colors
from reportlab.lib.utils import ImageReader
import re

HERE=Path(__file__).resolve().parent
ROOT=HERE.parent
OUT=ROOT/'NOT_Gate_Report.pdf'
W,H=A4
c=canvas.Canvas(str(OUT),pagesize=A4)
c.setTitle('NOT Gate - Verified VHDL and Logisim Results')
c.setAuthor('HUANGZE')

def heading(title,page):
    c.setFillColor(colors.HexColor('#64748b'));c.setFont('Helvetica',8)
    c.drawString(48,H-30,'VHDL Course - NOT Gate Assignment')
    c.drawRightString(W-48,28,f'Page {page}')
    c.setStrokeColor(colors.HexColor('#cbd5e1'));c.line(48,H-38,W-48,H-38)
    c.setFillColor(colors.HexColor('#1d4ed8'));c.setFont('Helvetica-Bold',20)
    c.drawString(48,H-78,title)

def line(text,x,y,size=10,font='Helvetica'):
    c.setFillColor(colors.HexColor('#1e293b'));c.setFont(font,size);c.drawString(x,y,text)

def code(lines,x,y,size=9):
    for text in lines.splitlines():line(text,x,y,size,'Courier');y-=14
    return y

def image(path,x,y,maxw,maxh):
    r=ImageReader(str(path));w,h=r.getSize();s=min(maxw/w,maxh/h)
    c.drawImage(r,x+(maxw-w*s)/2,y+(maxh-h*s)/2,width=w*s,height=h*s)

heading('NOT Gate: Design and Verification',1)
line('Student: HUANGZE     Student ID: 2024095705',48,H-112,12,'Helvetica-Bold')
line('Verified revision: 18 November 2026',48,H-135)
line('Function: y is the logical inverse of a.',48,H-177,12)
line('Synthesizable VHDL source: not_gate.vhd',48,H-210,11,'Helvetica-Bold')
source=(ROOT/'not_gate.vhd').read_text(encoding='utf-8')
code(source,60,H-235)
line('Truth table',48,340,12,'Helvetica-Bold')
for i,(a,y) in enumerate([('a','y'),('0','1'),('1','0')]):
    line(a,70,315-i*23,12);line(y,160,315-i*23,12)
line('Verification method',48,210,12,'Helvetica-Bold')
for i,t in enumerate([
    'GHDL compiles and synthesizes the unchanged Boolean design.',
    'tb_not_gate.vhd tests 0, 1, 0, 1 and asserts every expected output.',
    'The Logisim main circuit uses one native NOT gate, with its real input',
    'and output ports connected. It needs no external VHDL simulator.',
    'The same four binary vectors are checked by the actual Logisim engine.'
]):line(t,48,185-i*17)
c.showPage()

heading('Logisim: Actual Simulated States',2)
line('Main circuit: not_gate.circ (Logisim-evolution 5.0.0)',48,H-112,11)
line('Input a = 0: observed output y = 1',48,H-155,12,'Helvetica-Bold')
image(HERE/'not_gate_state1.png',48,H-340,W-96,160)
line('Input a = 1: observed output y = 0',48,H-400,12,'Helvetica-Bold')
image(HERE/'not_gate_state2.png',48,H-585,W-96,160)
line('Figures rendered natively from the loaded circuit state after propagation.',48,155,9)
line('Logisim result: 4/4 vectors PASS; no oscillation.',48,126,11,'Helvetica-Bold')
c.showPage()

heading('VHDL Waveform and Test Evidence',3)
lines=(HERE/'not_gate.vcd').read_text().splitlines()
ids={};changes={'a':[],'y':[]};t=0
for s in lines:
    if s.startswith('$var '):
        p=s.split();name=p[4]
        if name in changes and name not in ids.values():ids[p[3]]=name
    elif s.startswith('#'):t=int(s[1:])/1e6
    elif s and s[0] in '01' and s[1:] in ids:changes[ids[s[1:]]].append((t,int(s[0])))
end=max(40,t);left,right=100,W-55;top=H-180
for tick in range(0,41,5):
    x=left+(right-left)*tick/end
    c.setStrokeColor(colors.HexColor('#e2e8f0'));c.line(x,top-110,x,top+30)
    line(str(tick),x-3,top-135,8)
line('Time (ns)',right-45,top-155,9)
for i,name in enumerate(['a','y']):
    mid=top-i*80;line(name,60,mid,12,'Helvetica-Bold')
    c.setStrokeColor(colors.HexColor('#2563eb' if i==0 else '#059669'));c.setLineWidth(2)
    vals=changes[name]
    for idx,(t,v) in enumerate(vals):
        next_t=vals[idx+1][0] if idx+1<len(vals) else end
        x1=left+(right-left)*t/end;x2=left+(right-left)*next_t/end;y=mid+(15 if v else -15)
        c.line(x1,y,x2,y)
        if idx+1<len(vals):c.line(x2,y,x2,mid+(15 if vals[idx+1][1] else -15))
line('Waveform plotted from not-gate-tests/not_gate.vcd generated by GHDL.',48,top-185,9)
line('GHDL results',48,top-225,12,'Helvetica-Bold')
log=(HERE/'ghdl.log').read_text(encoding='utf-8-sig')
notes=[re.sub(r'^.*?:\d+:\d+:','',s) for s in log.splitlines() if 'report note' in s or 'simulation finished' in s]
code('\n'.join(notes),48,top-250,8)
line('Reproduce both implementations',48,185,12,'Helvetica-Bold')
code('./run_not_gate.ps1',48,161,10)
line('Requires GHDL, JDK 21+, and Logisim-evolution 5.0.0.',48,131,9)
line('Raw logs: not-gate-tests/ghdl.log and not-gate-tests/logisim.log',48,112,9)
line('Binary truth-table behavior is verified; this report does not claim',48,83,9)
line('that importing VHDL into Logisim alone runs its external VHDL simulator.',48,69,9)
c.save()
print(OUT)
